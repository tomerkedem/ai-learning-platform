// Данные лаборатории Logits и Softmax для главы 8 (Logits & Softmax),
// русская локализация. Иврит - язык-источник и определяет форму типа.
//
// Главная идея: прежде чем модель выбирает продолжение, она даёт каждому
// варианту сырую оценку (logit). Softmax превращает эти оценки в распределение
// вероятностей: каждое продолжение получает процент, и вместе они дают 100.
// Изменение контекстной детали сдвигает оценки, а значит, и проценты. Учащийся
// также может вручную настроить любую оценку и сразу увидеть, как меняются
// вероятности.
//
// Все оценки и проценты - это только учебная иллюстрация, а не реальный вывод
// модели. Продолжения показаны целыми фразами для удобства чтения, но они
// представляют соревнование за следующий токен, а не точный внутренний след.
//
// Без длинного тире, без среднего тире, без длинного русского тире.

/** Одно возможное продолжение из нескольких соперников. */
export interface LabContinuation {
    /** Стабильный идентификатор, не переводится. */
    id: string;
    /** Метка продолжения, например "задержалась". */
    label: string;
}

/** Контекстная деталь, которую можно выбрать. Каждая деталь задаёт свою сырую оценку каждому продолжению. */
export interface LabContext {
    /** Стабильный идентификатор, не переводится. */
    id: string;
    /** Метка кнопки. */
    control: string;
    /** Добавка к контексту, которая входит в промпт перед "Посылка, вероятно...". Пусто в нейтральном режиме. */
    promptExtra?: string;
    /** Короткое пояснение: почему эта деталь сдвигает оценки. */
    note: string;
    /** Соответствие идентификатора продолжения его сырой оценке в этом режиме (учебная иллюстрация). */
    scores: Record<string, number>;
}

export interface LogitsSoftmaxLabContent {
    /** Заголовки секции на странице (над компонентом). */
    sectionEyebrow: string;
    sectionTitle: string;
    sectionIntro: string;
    /** Внутренний заголовок компонента. */
    heading: string;
    /** Структурная латинская подпись (остаётся как есть на любом языке). */
    kicker: string;
    /** Начало предложения, которое модель завершает. */
    promptBase: string;
    promptLabel: string;
    pickContextLabel: string;
    scoreLabel: string;
    probabilityLabel: string;
    topLabel: string;
    adjustTitle: string;
    adjustHint: string;
    resetScores: string;
    softmaxNoteTitle: string;
    softmaxNote: string;
    continuationNote: string;
    disclaimer: string;
    /** Метки для программ чтения с экрана. */
    sr: { increase: string; decrease: string; contextGroup: string };
    continuations: LabContinuation[];
    contexts: LabContext[];
}

