/**
 * פילוח חזותי מפורש לזוג השלילה, לשפה שבה הפילוח האוטומטי אינו מזהה נכון את השלילה.
 *
 * הרכיב מפלח את שני המשפטים ל-"מילים" ומדגיש את האסימונים הייחודיים למשפט המקורי.
 * זה עובד בשפות שבהן השלילה היא מילה עצמאית (he "לא", en "not", es "no", ru "не"),
 * וגם בערבית, שבה נכון להדגיש גם את "لم" וגם את צורת הפועל שהשתנתה ("يصل"). ביפנית
 * הפילוח האוטומטי נכשל: הוא קורע את גזע הפועל ומדגיש חלק מסמן הזמן, ולכן היא מספקת
 * כאן פילוח מפורש. אין להשתמש בזה כדי לעקוף פילוח שעובד.
 *
 * base ו-opposite הם הפילוח לעין בלבד. המשפט הטבעי והרציף (phrases) הוא שנשלח
 * להקראה, ל-sr-only ול-aria-label, ולכן אסור לשתול כאן רווחים מלאכותיים. הרכיב
 * מאמת שהחיבור מחדש (join) מחזיר את המשפט המקורי בדיוק, ואם לא, נופל לפילוח האוטומטי.
 */
export interface NegationVisual {
    /** פילוח חזותי של המשפט המקורי. join('') חייב להחזיר את phrases[base] בדיוק. */
    base: string[];
    /** פילוח חזותי של משפט הנגד. join('') חייב להחזיר את phrases[opposite] בדיוק. */
    opposite: string[];
    /** האסימונים מתוך base שמודגשים כציר השלילה. חייבים להופיע ב-base. */
    pivot: string[];
}

