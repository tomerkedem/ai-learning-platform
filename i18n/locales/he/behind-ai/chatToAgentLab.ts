// (ChatToAgentLabContent) שכל שאר השפות חייבות לעמוד בה.
//
// הרעיון המרכזי: אותה בקשה בדיוק, "בדוק מה קורה עם החבילה ועדכן את הלקוח", נענית
// בארבעה מצבים שונים:
//   1. צ'אט: מקבל קלט ומחזיר תשובה, בלי כלי ובלי פעולה.
//   2. Agent, מידע חסר: אין מספר מעקב, אז הוא שואל במקום לנחש.
//   3. Agent, שימוש בכלי: יש מספר מעקב, אז הוא בוחר כלי מעקב ומנסח לפי התוצאה.
//   4. Agent, דרוש אישור: הצעד הבא הוא שליחה ללקוח, פעולה רגישה שנעצרת לאישור.
// בכל מצב רואים את מסלול הצעדים, כרטיס כלי או תוצאה כשרלוונטי, את הפלט, ותג הרשאה.
//
// דטרמיניסטי לחלוטין: אין אקראיות, אין קריאת מודל אמיתית, אין חיבור אמיתי למערכת
// מעקב, אין שליחת הודעה אמיתית, ואין הצגת שרשרת חשיבה נסתרת. כל הטקסט תלוי-השפה
// מגיע מ-data לפי locale, והכיוון (RTL/LTR) מ-dir. סדר המצבים ומזהיהם נשאר קבוע,
// וכן מפתחות ה-modeType שהם מבניים.
//
// אין מקף ארוך (U+2014), אין מקף בינוני (U+2013), אין נקודה-פסיק בעברית ואין אזכור שנה.

/** סוג המצב. מבני, קובע אייקון וגוון לתג ההרשאה, אינו מתורגם. */
export type AgentModeType = 'chat' | 'askInfo' | 'toolLookup' | 'approval' | 'toolError';

/** סטטוס האימות. מבני, קובע אייקון וגוון, אינו מתורגם. */
export type VerificationStatus = 'passed' | 'pending' | 'failed';

/** כרטיס כלי ותוצאה, מוצג רק במצב שבו ה-Agent משתמש בכלי. */
export interface AgentToolCard {
    /** שם הכלי (דוגמה לימודית). */
    name: string;
    /** תווית הקלט לכלי. */
    inputLabel: string;
    /** הקלט שנשלח לכלי (דוגמה). */
    input: string;
    /** תווית התוצאה. */
    resultLabel: string;
    /** שורות התוצאה (דוגמה לימודית, לא נתון אמיתי). */
    result: string[];
}

/** בלוק ניסיון חוזר וגבול, למצב שבו כלי נכשל. מראה שהניסיונות חסומים. */
export interface AgentRetry {
    /** תווית הבלוק, למשל "ניסיון חוזר". */
    attemptsLabel: string;
    /** שורות הניסיונות (ראשון נכשל, ניסיון חוזר אחד נכשל גם). */
    attempts: string[];
    /** הצהרת הגבול המפורשת, למשל "ניסיון חוזר אחד בלבד". */
    limitNote: string;
    /** למה עוצרים אחרי הגבול. */
    stopReason: string;
}

/** שורת אימות: האם התקבלה תוצאה נצפית שאפשר לסמוך עליה. */
export interface AgentVerification {
    /** סטטוס מבני: אומת, ממתין, נכשל. קובע אייקון וגוון. */
    status: VerificationStatus;
    /** מה אומת, או למה עוד לא ניתן לאמת. */
    text: string;
}

/** מצב אחד של המעבדה: איך אותה בקשה נענית, ובאיזה מסלול. */
export interface AgentMode {
    /** מזהה יציב, אינו מתורגם. */
    id: string;
    /** סוג המצב. מבני, קובע אייקון וגוון לתג. */
    modeType: AgentModeType;
    /** תווית הכפתור המקוצרת בבורר המצבים. */
    control: string;
    /** תווית תג ההרשאה, למשל "תשובה בלבד" או "דרוש אישור". */
    badgeLabel: string;
    /** כותרת המצב. */
    title: string;
    /** משפט אחד שמתאר את המצב. */
    summary: string;
    /** מסלול הצעדים הגלוי במצב הזה. */
    steps: string[];
    /** כרטיס כלי ותוצאה, כשהמצב כולל שימוש בכלי. */
    tool?: AgentToolCard;
    /** בלוק ניסיון חוזר וגבול, כשהמצב הוא כשל כלי. אופציונלי. */
    retry?: AgentRetry;
    /** תווית הפלט, למשל "התשובה" או "טיוטה ללקוח". */
    outputLabel: string;
    /** הפלט של המצב: תשובה, שאלה, ניסוח, טיוטה או דיווח כישלון. */
    output: string;
    /** הערה נוספת, למשל למה עוצרים לאישור. אופציונלי. */
    note?: string;
    /** שורת אימות: האם התקבלה תוצאה נצפית שאפשר לסמוך עליה. אופציונלי. */
    verification?: AgentVerification;
    /** השורה התחתונה של המצב. */
    takeaway: string;
}

export interface ChatToAgentLabContent {
    /** כותרות הסקשן בעמוד (מעל הרכיב). */
    sectionEyebrow: string;
    sectionTitle: string;
    sectionIntro: string;
    /** כותרת פנימית של הרכיב. */
    heading: string;
    /** תת-כותרת לטינית מבנית (נשארת כמות שהיא בכל שפה). */
    kicker: string;
    /** כרטיס הבקשה הקבוע מעל המצבים. */
    requestLabel: string;
    request: string;
    /** תווית בורר המצבים. */
    modeSelectLabel: string;
    /** תוויות הפאנלים הפנימיים בכל מצב. */
    stepsLabel: string;
    permissionLabel: string;
    takeawayLabel: string;
    /** תווית שורת האימות. */
    verificationLabel: string;
    /** מילות סטטוס האימות, לפי סטטוס מבני. */
    verificationStatusLabels: { passed: string; pending: string; failed: string };
    /** הבהרה שהדוגמאות לימודיות בלבד. */
    disclaimer: string;
    /** תוויות לקוראי מסך. */
    sr: { modeGroup: string; modeDetail: string };
    modes: AgentMode[];
}

