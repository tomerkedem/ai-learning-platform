/** סוג השכבה. מבני, קובע אייקון וגוון לתג השכבה, אינו מתורגם. */
export type LearnLayerType = 'sameChat' | 'newChat' | 'memory' | 'training';

/** שכבת למידה אחת: מה המודל רואה, איך הוא עונה, ומה השתנה או לא השתנה. */
export interface LearnLayer {
    /** מזהה יציב, אינו מתורגם. */
    id: string;
    /** סוג השכבה. מבני, קובע אייקון וגוון לתג. */
    layerType: LearnLayerType;
    /** תווית הכפתור המקוצרת בבורר השכבות. */
    control: string;
    /** תווית התג המילולית, למשל "הקשר נוכחי". */
    badgeLabel: string;
    /** כותרת השכבה. */
    title: string;
    /** משפט אחד שמתאר את השכבה. */
    summary: string;
    /** מה המודל רואה עכשיו בשכבה הזאת (רשימת פריטים). */
    sees: string[];
    /** תשובת המודל או התוצאה בשכבה הזאת (דוגמה לימודית). */
    answer: string;
    /** מה השתנה בשכבה הזאת. */
    changed: string;
    /** מה לא השתנה בשכבה הזאת. */
    unchanged: string;
    /** השורה התחתונה של השכבה. */
    takeaway: string;
}

export interface DoesAiLearnLabContent {
    /** כותרות הסקשן בעמוד (מעל הרכיב). */
    sectionEyebrow: string;
    sectionTitle: string;
    sectionIntro: string;
    /** כותרת פנימית של הרכיב. */
    heading: string;
    /** תת-כותרת לטינית מבנית (נשארת כמות שהיא בכל שפה). */
    kicker: string;
    /** כרטיס התרחיש הקבוע מעל השכבות. */
    scenario: {
        label: string;
        aiSaidLabel: string;
        aiSaid: string;
        userCorrectionLabel: string;
        userCorrection: string;
        aiRevisedLabel: string;
        aiRevised: string;
    };
    /** תווית בורר השכבות. */
    layerSelectLabel: string;
    /** תוויות הפאנלים הפנימיים בכל שכבה. */
    seesLabel: string;
    answerLabel: string;
    changedLabel: string;
    unchangedLabel: string;
    takeawayLabel: string;
    /** הבהרה שהדוגמאות לימודיות בלבד. */
    disclaimer: string;
    /** תוויות לקוראי מסך. */
    sr: { layerGroup: string; layerDetail: string };
    layers: LearnLayer[];
}

