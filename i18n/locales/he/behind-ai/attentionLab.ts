// המשקלים ואינדקסי הזוג (pair) תלויים בשפה כי הם נגזרים מסדר המילים במשפט. בכל שפה
// המשפט שונה, מספר המילים שונה, וכיוון הקריאה שונה (RTL מול LTR), ולכן variants
// חייבים להיות מוגדרים לכל שפה בנפרד. מיפוי הגוונים (tension -> צבע) נשאר ברכיב.
