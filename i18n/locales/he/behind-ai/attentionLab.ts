/** עוצמת הקשר בין שני החלקים המרכזיים במצב נתון. */
export type LabTension = 'high' | 'medium' | 'low' | 'shifted';

export interface LabVariant {
    /** מזהה יציב, אינו מתורגם. */
    id: string;
    /** תווית הכפתור: העריכה עצמה. */
    control: string;
    /** המשפט המלא במצב הזה (לתצוגה ולהקראה). */
    sentence: string;
    /** מילות המשפט בסדר קריאה. */
    tokens: string[];
    /** משקל קשב לכל טוקן (0..1), כתוב ידנית להמחשה. */
    weights: number[];
    /** שני האינדקסים שמרכיבים את הקשר המרכזי במצב הזה. */
    pair: [number, number];
    /** עוצמת הקשר בין החלקים (0..1). */
    pairStrength: number;
    tension: LabTension;
    /** כיתוב שמסביר מה השתנה ולמה הקשב זז. */
    caption: string;
}

export interface AttentionLabContent {
    /** כותרת הסקשן בעמוד (מעל הרכיב). */
    sectionEyebrow: string;
    sectionTitle: string;
    sectionIntro: string;
    /** כותרת פנימית של הרכיב. */
    heading: string;
    /** תת-כותרת לטינית מבנית (נשארת כמות שהיא בכל שפה). */
    kicker: string;
    pickHint: string;
    nowLabel: string;
    relationLabel: string;
    disclaimer: string;
    tensionLabels: Record<LabTension, string>;
    /** תוויות לקוראי מסך. */
    sr: { attention: string; percent: string; inPair: string; strength: string; group: string };
    variants: LabVariant[];
}

