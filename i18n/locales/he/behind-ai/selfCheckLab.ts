/** מצב שורת בדיקה ברשימת הבדיקה העצמית: עבר, אזהרה, נכשל. מבני, אינו מתורגם. */
export type CheckState = 'pass' | 'warn' | 'fail';

/** מצב טענה בטיוטה: נתמכת במקור, לא נתמכת, או עובדה זמינה שלא נוצלה. מבני, אינו מתורגם. */
export type ClaimState = 'supported' | 'unsupported' | 'missing';

/** תג מצב הטיוטה. מבני, קובע אייקון וגוון, אינו מתורגם. */
export type DraftBadge = 'overclaim' | 'overcautious' | 'checked' | 'needsSource';

/** שורה אחת בכרטיס המקור. missing מסמן ערך חסר (למשל "לא זמין") לגוון מושתק. */
export interface SourceRow {
    label: string;
    value: string;
    /** האם הערך חסר במקור. מבני, קובע גוון בלבד. */
    missing?: boolean;
}

/** צ׳יפ טענה בתוך הטיוטה: הטקסט של הטענה, מצבה מול המקור, והסבר קצר. */
export interface ClaimChip {
    /** מזהה יציב, אינו מתורגם. */
    id: string;
    /** טקסט הטענה כפי שהיא מופיעה בטיוטה. */
    text: string;
    /** מצב הטענה מול המקור. מבני, קובע אייקון וגוון. */
    state: ClaimState;
    /** הסבר קצר למה הטענה נתמכת, לא נתמכת, או הוחמצה. */
    note: string;
}

/** שורת בדיקה אחת ברשימת הבדיקה העצמית. */
export interface LabCheck {
    /** מזהה יציב, אינו מתורגם. סדר השורות זהה בכל הטיוטות. */
    id: string;
    /** תוצאת הבדיקה. קובעת את האייקון והגוון ברכיב. מבני. */
    state: CheckState;
    /** שאלת הבדיקה, למשל "ממציאה שעות חג?". */
    label: string;
    /** הסבר קצר על התוצאה. */
    note: string;
}

/** טיוטת תשובה אחת: הניסוח, הטענות שבה, רשימת הבדיקה, והתשובה המתוקנת. */
export interface DraftMode {
    /** מזהה יציב, אינו מתורגם. */
    id: string;
    /** תווית הכפתור המקוצרת. */
    control: string;
    /** תג מצב הטיוטה. מבני, קובע אייקון וגוון. */
    badge: DraftBadge;
    /** תווית התג המילולית, למשל "טענה לא נתמכת". */
    badgeLabel: string;
    /** משפט אחד שמתאר מה מאפיין את הטיוטה הזו. */
    summary: string;
    /** טקסט הטיוטה שהמודל ניסח. */
    draft: string;
    /** הטענות המסומנות בתוך הטיוטה. */
    claims: ClaimChip[];
    /** שורות הבדיקה העצמית של הטיוטה. */
    checks: LabCheck[];
    /** משפט אחד שמסכם מה הבדיקה מצאה. */
    issue: string;
    /** התשובה המתוקנת אחרי הבדיקה. */
    revised: string;
    /** משפט אחד שמסביר מה השתנה בתשובה המתוקנת. */
    revisedNote: string;
    /** שורת מסקנה קצרה מהטיוטה הזו. */
    takeaway: string;
}

export interface SelfCheckLabContent {
    /** כותרות הסקשן בעמוד (מעל הרכיב). */
    sectionEyebrow: string;
    sectionTitle: string;
    sectionIntro: string;
    /** כותרת פנימית של הרכיב. */
    heading: string;
    /** תת-כותרת לטינית מבנית (נשארת כמות שהיא בכל שפה). */
    kicker: string;
    /** תווית ותוכן שאלת הלקוח הקבועה. */
    questionLabel: string;
    question: string;
    /** כרטיס המקור הקבוע, משותף לכל הטיוטות. */
    sourceLabel: string;
    sourceCaption: string;
    sourceNote: string;
    sourceRows: SourceRow[];
    /** תוויות הפאנלים הפנימיים. */
    draftLabel: string;
    claimsLabel: string;
    checklistLabel: string;
    issueLabel: string;
    revisedLabel: string;
    takeawayLabel: string;
    /** הבהרה שהדוגמאות לימודיות בלבד. */
    disclaimer: string;
    /** תוויות לקוראי מסך. */
    sr: { draftGroup: string; checks: string };
    modes: DraftMode[];
}

