/** מצב שורת בדיקת עיגון: עבר, אזהרה, נכשל. מבני, אינו מתורגם. */
export type CheckState = 'pass' | 'warn' | 'fail';

/** תג מצב העיגון של מצב המקור. מבני, קובע אייקון וגוון, אינו מתורגם. */
export type GroundingBadge = 'ungrounded' | 'grounded' | 'incomplete' | 'contradiction';

/** שורת בדיקת עיגון אחת בתוך פאנל בדיקת העיגון. */
export interface LabCheck {
    /** מזהה יציב, אינו מתורגם. */
    id: string;
    /** מצב הבדיקה. קובע את האייקון והגוון ברכיב. מבני. */
    state: CheckState;
    /** שאלת הבדיקה, למשל "נשענת על מקור?". */
    label: string;
    /** הסבר קצר על התוצאה. */
    note: string;
}

/** שורה אחת בכרטיס המקור. missing מסמן ערך חסר (למשל "לא זמין") לגוון מושתק. */
export interface SourceRow {
    label: string;
    value: string;
    /** האם הערך חסר במקור. מבני, קובע גוון בלבד. */
    missing?: boolean;
}

/** כרטיס סטטוס המעקב לדוגמה של מצב מקור. */
export interface SampleSource {
    label: string;
    caption: string;
    rows: SourceRow[];
    note: string;
}

/** מצב מקור אחד: בלי מקור, עם מקור, מקור חסר, או מקור סותר. */
export interface SourceMode {
    /** מזהה יציב, אינו מתורגם. */
    id: string;
    /** תווית הכפתור המקוצרת. */
    control: string;
    /** תג מצב העיגון. מבני, קובע אייקון וגוון. */
    badge: GroundingBadge;
    /** תווית התג המילולית, למשל "מעוגן". */
    badgeLabel: string;
    /** משפט אחד שמתאר מה מצב המקור הזה מראה. */
    summary: string;
    /** כרטיס המקור של המצב. חסר במצב "בלי מקור". */
    source?: SampleSource;
    /** התשובה שהמודל מחזיר במצב הזה. */
    answer: string;
    /** משפט אחד שמתאר מה מאפיין את התשובה הזו. */
    answerSummary: string;
    /** שורות בדיקת העיגון של התשובה. */
    checks: LabCheck[];
    /** מה התשובה יכולה לומר בגבולות המקור. */
    maySay: string;
    /** מה אסור לתשובה להמציא מעבר למקור. */
    mustNotInvent: string;
    /** שורת מסקנה קצרה מהמצב הזה. */
    takeaway: string;
}

export interface GroundingLabContent {
    /** כותרות הסקשן בעמוד (מעל הרכיב). */
    sectionEyebrow: string;
    sectionTitle: string;
    sectionIntro: string;
    /** כותרת פנימית של הרכיב. */
    heading: string;
    /** תת-כותרת לטינית מבנית (נשארת כמות שהיא בכל שפה). */
    kicker: string;
    /** תווית ותוכן שאלת הלקוח הקבועה. */
    questionLabel: string;
    question: string;
    /** תווית בורר מצב המקור. */
    modeLabel: string;
    /** תוויות פנימיות של הפאנלים. */
    answerLabel: string;
    groundingCheckLabel: string;
    maySayLabel: string;
    mustNotInventLabel: string;
    takeawayLabel: string;
    /** כרטיס "אין מקור" שמוצג במצב בלי מקור. */
    noSourceLabel: string;
    noSourceNote: string;
    /** הבהרה שהדוגמאות לימודיות בלבד. */
    disclaimer: string;
    /** תוויות לקוראי מסך. */
    sr: { modeGroup: string; checks: string };
    modes: SourceMode[];
}

