/** מצב שורת בדיקת עובדות: עבר, אזהרה, נכשל. מבני, אינו מתורגם. */
export type CheckState = 'pass' | 'warn' | 'fail';

/** רמת סיכון לתווית הצבע. מבני, אינו מתורגם. */
export type RiskLevel = 'low' | 'medium' | 'high';

/** שורת בדיקת עובדות אחת בתוך פאנל ה-fact-check. */
export interface LabCheck {
    /** מזהה יציב, אינו מתורגם. */
    id: string;
    /** מצב הבדיקה. קובע את האייקון והגוון ברכיב. מבני. */
    state: CheckState;
    /** שאלת הבדיקה, למשל "מקור סטטוס נבדק?". */
    label: string;
    /** הסבר קצר על התוצאה. */
    note: string;
}

/** סגנון תשובה אחד: בטוחה אך לא מבוססת, זהירה, מבוססת מקור, או מידע חסר. */
export interface AnswerMode {
    /** מזהה יציב, אינו מתורגם. */
    id: string;
    /** תווית הכפתור המקוצרת. */
    control: string;
    /** רמת הסיכון של שליחת התשובה כפי שהיא. מבני, קובע גוון. */
    risk: RiskLevel;
    /** תווית הסיכון המילולית, למשל "סיכון גבוה". */
    riskLabel: string;
    /** הסבר קצר למה זו רמת הסיכון הזו. */
    riskNote: string;
    /** התשובה שהמודל מחזיר בסגנון הזה. */
    answer: string;
    /** משפט אחד שמתאר מה מאפיין את התשובה הזו. */
    answerSummary: string;
    /** שורות בדיקת העובדות של התשובה. */
    checks: LabCheck[];
    /** מה חסר או מה הצעד הנכון. */
    missing: string;
    /** שורת מסקנה קצרה מהסגנון הזה. */
    takeaway: string;
    /** האם להציג את כרטיס המקור לדוגמה (רק בסגנון המבוסס). מבני. */
    showSource?: boolean;
}

/** כרטיס סטטוס המעקב לדוגמה, מוצג בסגנון המבוסס בלבד. */
export interface SampleSource {
    label: string;
    caption: string;
    rows: { label: string; value: string }[];
    note: string;
}

export interface HallucinationsLabContent {
    /** כותרות הסקשן בעמוד (מעל הרכיב). */
    sectionEyebrow: string;
    sectionTitle: string;
    sectionIntro: string;
    /** כותרת פנימית של הרכיב. */
    heading: string;
    /** תת-כותרת לטינית מבנית (נשארת כמות שהיא בכל שפה). */
    kicker: string;
    /** תווית ותוכן שאלת הלקוח הקבועה. */
    questionLabel: string;
    question: string;
    /** תווית בורר הסגנון. */
    modeLabel: string;
    /** תוויות פנימיות של הפאנלים. */
    answerLabel: string;
    riskLabel: string;
    factCheckLabel: string;
    missingLabel: string;
    takeawayLabel: string;
    /** כרטיס המקור לדוגמה. */
    source: SampleSource;
    /** הבהרה שהדוגמאות לימודיות בלבד. */
    disclaimer: string;
    /** תוויות לקוראי מסך. */
    sr: { modeGroup: string; checks: string };
    modes: AnswerMode[];
}

