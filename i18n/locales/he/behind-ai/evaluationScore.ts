/** מזהה סוג מקרה. מבני, קובע אייקון וגוון, ואינו מתורגם. */
export type ScoreCaseTypeId = 'direct' | 'noTracking' | 'multiQuestion' | 'pressure';

/** הטקסט של סוג מקרה אחד בפירוק. */
export interface ScoreCaseTypeText {
    /** שם סוג המקרה, כפי שמוצג בכרטיס. */
    name: string;
    /** משפט אחד שמסביר מה מאפיין את סוג המקרה הזה. */
    note: string;
}

/** שאלה עם שלוש אפשרויות. התשובה הנכונה היא אינדקס מבני ברכיב, לא כאן. */
export interface ScoreChoice {
    question: string;
    /** בדיוק שלוש אפשרויות, בסדר קבוע בכל השפות (האינדקס הנכון מבני). */
    options: [string, string, string];
}

export interface EvaluationScoreContent {
    panel: {
        eyebrow: string;
        title: string;
        intro: string;
        /** תוויות הכותרת המספרית. */
        headlineLabel: string;
        totalLabel: string;
        passedLabel: string;
        /** הניחוש שלפני החשיפה, וההסבר שנפתח אחריו. */
        guess: ScoreChoice;
        guessExplain: string;
        revealButton: string;
        /** תוויות הפירוק לפי סוג מקרה. */
        breakdownLabel: string;
        casesLabel: string;
        rateLabel: string;
        weakTypeLabel: string;
        excludedLabel: string;
        caseTypes: Record<ScoreCaseTypeId, ScoreCaseTypeText>;
        /** בקרת היקף סט הבדיקה. */
        coverageLabel: string;
        coverageWide: string;
        coverageThin: string;
        coverageNote: string;
        /** מה השתנה ומה לא. הלב של הרגע הלימודי. */
        changedLabel: string;
        changed: string;
        unchangedLabel: string;
        unchanged: string;
        /** בדיקת ההבנה שבתוך הלוח, נפתחת רק אחרי שהלומד הפעיל את הבקרה. */
        lock: ScoreChoice;
        lockSuccess: string;
        /** התובנה הסוגרת של הלוח. */
        insight: string;
        note: string;
        /** תוויות לקוראי מסך. */
        sr: { coverageGroup: string; breakdown: string };
    };
    bias: {
        eyebrow: string;
        title: string;
        lead: string;
        body: string;
        ask: string;
    };
}

