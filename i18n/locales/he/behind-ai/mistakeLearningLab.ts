// אין מקף ארוך (U+2014), אין מקף בינוני (U+2013), אין נקודה-פסיק בעברית ואין אזכור שנה.

/** רמת השיפור. מבני, קובע אייקון וגוון לתג המצב, אינו מתורגם. */
export type MistakeLevel = 'context' | 'system' | 'training' | 'evaluation';

/** גוון שלב בתהליך. מבני, קובע אייקון וגוון, אינו מתורגם. */
export type StepTone = 'wrong' | 'context' | 'system' | 'training' | 'eval' | 'good';

/** שורה אחת בכרטיס המקור. missing מסמן ערך חסר (למשל "לא זמין") לגוון מושתק. */
export interface SourceRow {
    label: string;
    value: string;
    /** האם הערך חסר במקור. מבני, קובע גוון בלבד. */
    missing?: boolean;
}

/** שלב אחד בתהליך של המצב הנבחר: תווית קצרה, משפט הסבר, וגוון מבני. */
export interface FlowStep {
    /** מזהה יציב, אינו מתורגם. סדר השלבים נשמר. */
    id: string;
    /** תווית קצרה לשלב, למשל "תשובה ראשונה". */
    label: string;
    /** משפט אחד שמתאר מה קורה בשלב. */
    text: string;
    /** גוון השלב. מבני, קובע אייקון וגוון. */
    tone: StepTone;
}

/** כרטיס לפני ואחרי, למצבים שבהם יש השוואה ישירה בין שתי תשובות או גרסאות. */
export interface BeforeAfter {
    beforeLabel: string;
    before: string;
    afterLabel: string;
    after: string;
}

/** מצב שיפור אחד: רמה, שלבי תהליך, ומה השתפר מול מה שלא. */
export interface MistakeMode {
    /** מזהה יציב, אינו מתורגם. */
    id: string;
    /** רמת השיפור. מבני, קובע אייקון וגוון לתג. */
    level: MistakeLevel;
    /** תווית הכפתור המקוצרת בבורר המצבים. */
    control: string;
    /** תווית התג המילולית, למשל "תיקון בהקשר". */
    badgeLabel: string;
    /** כותרת המצב. */
    title: string;
    /** משפט אחד שמתאר מה מאפיין את המצב הזה. */
    summary: string;
    /** שלבי התהליך של המצב, לפי הסדר. */
    steps: FlowStep[];
    /** כרטיס לפני ואחרי, אם רלוונטי למצב. */
    beforeAfter?: BeforeAfter;
    /** מה השתפר במצב הזה. */
    improved: string;
    /** מה לא בהכרח השתפר במצב הזה. */
    notImproved: string;
    /** שורת מסקנה קצרה מהמצב הזה. */
    takeaway: string;
}

export interface MistakeLearningLabContent {
    /** כותרות הסקשן בעמוד (מעל הרכיב). */
    sectionEyebrow: string;
    sectionTitle: string;
    sectionIntro: string;
    /** כותרת פנימית של הרכיב. */
    heading: string;
    /** תת-כותרת לטינית מבנית (נשארת כמות שהיא בכל שפה). */
    kicker: string;
    /** הפנייה הקבועה של הלקוח. */
    scenarioLabel: string;
    scenario: string;
    /** כרטיס המקור הקבוע, משותף לכל המצבים. */
    sourceLabel: string;
    sourceCaption: string;
    sourceNote: string;
    sourceRows: SourceRow[];
    /** התשובה השגויה הראשונה הקבועה. */
    initialLabel: string;
    initialAnswer: string;
    /** התיקון הקבוע של הלומד. */
    correctionLabel: string;
    correction: string;
    /** תוויות הפאנלים הפנימיים. */
    modeLabel: string;
    flowLabel: string;
    improvedLabel: string;
    notImprovedLabel: string;
    takeawayLabel: string;
    /** הבהרה שהדוגמאות לימודיות בלבד. */
    disclaimer: string;
    /** תוויות לקוראי מסך. */
    sr: { modeGroup: string; steps: string };
    modes: MistakeMode[];
}

